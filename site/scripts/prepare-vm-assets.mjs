import { createHash } from "node:crypto";
import { execFile } from "node:child_process";
import { copyFile, mkdir, readFile, unlink, writeFile } from "node:fs/promises";
import path from "node:path";
import { promisify } from "node:util";

const ROOT = path.resolve(import.meta.dirname, "..");
const OUT = path.join(ROOT, "public", "vm");
const ALPINE = path.join(OUT, "alpine", "alpine-virt-3.21.3-x86.iso");
const ISO_URL = "https://dl-cdn.alpinelinux.org/alpine/v3.21/releases/x86/alpine-virt-3.21.3-x86.iso";
const ISO_SHA256 = "e837d1d67aced3157652a51f2c22bee582a95ad03863a6a25b5c1c1bbc9a3d84";
const PATCHED_ISO_SHA256 = "2e4bc5a30fe994b2dc4a24c0acb0b7079add91ff90e6600afa32eb00c1c2c205";
const BIOS = {
  "seabios.bin": ["https://raw.githubusercontent.com/copy/v86/master/bios/seabios.bin", "73e3f359102e3a9982c35fce98eb7cd08f18303ac7f1ba6ebfbe6cdc1c244d98"],
  "vgabios.bin": ["https://raw.githubusercontent.com/copy/v86/master/bios/vgabios.bin", "a4bc0d80cc3ca028c73dafa8fee396b8d054ce87ebd8abfbd31b06b437607880"],
};

const sha256 = (buffer) => createHash("sha256").update(buffer).digest("hex");
const exec = promisify(execFile);

async function download(url, expected) {
  const temporary = path.join(OUT, `.download-${process.pid}-${Math.random().toString(16).slice(2)}`);
  await exec("curl", ["--fail", "--location", "--proto", "=https", "--tlsv1.2", url, "--output", temporary]);
  const buffer = await readFile(temporary);
  await unlink(temporary);
  const actual = sha256(buffer);
  if (actual !== expected) throw new Error(`${url}: SHA-256 ${actual}, expected ${expected}`);
  return buffer;
}

async function verifiedFile(file, url, expected) {
  try {
    const current = await readFile(file);
    if (sha256(current) === expected) return;
  } catch {}
  const buffer = await download(url, expected);
  await writeFile(file, buffer);
}

await mkdir(path.dirname(ALPINE), { recursive: true });
await mkdir(OUT, { recursive: true });

for (const [name, [url, hash]] of Object.entries(BIOS)) await verifiedFile(path.join(OUT, name), url, hash);

// npm verifies the v86 package through package-lock.json; these are copied so
// the published site does not contact npm or another origin at runtime.
const v86 = path.join(ROOT, "node_modules", "v86");
await copyFile(path.join(v86, "build", "libv86.js"), path.join(OUT, "libv86.js"));
await copyFile(path.join(v86, "build", "v86.wasm"), path.join(OUT, "v86.wasm"));
await copyFile(path.join(v86, "LICENSE"), path.join(OUT, "V86-LICENSE.txt"));

// Patch Syslinux in place without rebuilding the ISO: replace an equally sized
// kernel argument string, dropping the unused USB boot module and enabling the
// serial console consumed by xterm.js.
let alpineReady = false;
try { alpineReady = sha256(await readFile(ALPINE)) === PATCHED_ISO_SHA256; } catch {}
if (!alpineReady) {
  const original = await download(ISO_URL, ISO_SHA256);
  const from = Buffer.from("modules=loop,squashfs,sd-mod,usb-storage quiet ");
  const to = Buffer.from("modules=loop,squashfs,sd-mod console=ttyS0,115200 ".padEnd(from.length));
  let offset = 0, replacements = 0;
  while ((offset = original.indexOf(from, offset)) >= 0) { to.copy(original, offset); replacements++; offset += from.length; }
  if (replacements !== 2) throw new Error(`Alpine boot arguments found ${replacements} times instead of 2`);
  if (sha256(original) !== PATCHED_ISO_SHA256) throw new Error("Patched Alpine ISO checksum changed unexpectedly");
  await writeFile(ALPINE, original);
}
await writeFile(`${ALPINE}.sha256`, `${PATCHED_ISO_SHA256}  ${path.basename(ALPINE)}\n`);

await writeFile(path.join(OUT, "README.txt"), [
  "Generated by scripts/prepare-vm-assets.mjs — do not edit.",
  `Alpine source: ${ISO_URL}`,
  "Patch: serial console enabled; unused usb-storage boot module removed.",
  "v86 source: npm package v86 (see package-lock.json and V86-LICENSE.txt).",
  "All generated files are served locally by the built static site.",
  "",
].join("\n"));
console.log(`VM assets prepared in ${path.relative(ROOT, OUT)}.`);
